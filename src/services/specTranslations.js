/** Return the specs object with Arabic labels/values where we know them. */
function translateSpecs(specs) {
  const out = {};
  for (const [k, v] of Object.entries(specs || {})) {
    const key = KEYS[String(k).trim()] || k;
    const val = VALUES[String(v).trim()] || v;
    // Two English keys can map to the same Arabic label (e.g. Power / Power Rating) — keep both.
    out[out[key] !== undefined ? `${key} (${k})` : key] = val;
  }
  return out;
}

